import { test, expect } from '@playwright/test';

test('diário, chamada, notas, publicação e consulta familiar', async ({ page, request }) => {
  const password = process.env.DEMO_PASSWORD!;
  expect(password).toBeTruthy();
  const origin = new URL(process.env.E2E_URL || 'http://localhost:3100').origin;
  await page.goto('/');
  await page.getByLabel('E-mail', { exact: true }).fill('director@aurora.example.com');
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar no portal', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible();
  const me = await (await page.request.get('/api/backend/me')).json();
  const base = `/api/backend/institutions/${me.memberships[0].institution_id}`;
  const get = async (path: string) => (await page.request.get(`${base}/${path}`)).json();
  const post = async (path: string, data: unknown) => { const r = await page.request.post(`${base}/${path}`, { headers: { Origin: origin }, data }); expect(r.status(), await r.text()).toBe(201); return r.json(); };
  const suffix = Date.now();
  const years = await get('academic-years?limit=100');
  const year = Array.from({ length: 65 }, (_, i) => 2030 + i).find(y => !years.some((r: { year: number }) => r.year === y))!;
  const calendar = await post('academic-years', { name: `Calendário diário ${suffix}`, year, start_date: `${year}-02-01`, end_date: `${year}-12-20` });
  const term = await post('academic-terms', { name: `Período diário ${suffix}`, academic_year_id: calendar.id, sequence: 1, start_date: `${year}-02-01`, end_date: `${year}-12-20` });
  const group = await post('classes', { name: `Turma diário ${suffix}`, academic_year: year, grade_level: '6º ano', shift: 'morning', capacity: 30 });
  const teacher = (await get('teachers'))[0]; const subject = (await get('subjects'))[0];
  await post('assignments', { class_id: group.id, teacher_id: teacher.id, subject_id: subject.id });
  const student = await post('students', { name: `Aluno diário ${suffix}`, birth_date: '2014-03-12' });
  await post('enrollments', { student_id: student.id, class_id: group.id });
  const guardian = (await get('guardians')).find((g: { email: string }) => g.email === 'familia@aurora.example.com');
  await post('guardian-links', { student_id: student.id, guardian_id: guardian.id, relationship: 'Responsável legal', verified: true });
  await page.getByRole('navigation').getByRole('button', { name: 'Diário e avaliações', exact: true }).click();
  await page.getByRole('button', { name: 'Configurar regra de avaliação' }).click();
  await page.getByLabel('Nome da regra', { exact: true }).fill(`Regra diário ${suffix}`);
  await page.getByLabel('Como aplicar a recuperação').selectOption('none');
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Abrir diário', exact: true }).click();
  await page.getByLabel('Turma e disciplina').selectOption({ label: `${group.name} · ${subject.name}` });
  await page.getByLabel('Período letivo', { exact: true }).selectOption(term.id);
  await page.getByLabel('Regra da escola').selectOption({ label: `Regra diário ${suffix}` });
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: new RegExp(group.name) }).click();
  await page.getByRole('button', { name: 'Registrar aula', exact: true }).click();
  await page.getByLabel('Data', { exact: true }).fill(`${year}-03-01`);
  await page.getByLabel('Conteúdo da aula').fill('Leitura e interpretação');
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar', exact: true }).click();
  await page.getByRole('button', { name: 'Fazer chamada' }).click();
  await page.getByRole('button', { name: 'Marcar todos presentes' }).click();
  await page.getByRole('button', { name: 'Salvar chamada' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('tab', { name: 'Avaliações e notas' }).click();
  await page.getByRole('button', { name: 'Criar avaliação', exact: true }).click();
  await page.getByLabel('Data', { exact: true }).fill(`${year}-03-02`);
  await page.getByLabel('Nome da avaliação').fill('Atividade de leitura');
  await page.getByRole('dialog').getByRole('button', { name: 'Salvar', exact: true }).click();
  await page.getByRole('button', { name: 'Lançar notas' }).click();
  await page.getByRole('dialog').getByRole('spinbutton').fill('8');
  await page.getByRole('button', { name: 'Salvar notas' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('tab', { name: 'Resultados e publicação' }).click();
  await expect(page.getByRole('cell', { name: '8.0', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Fechar diário', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Publicar boletim', exact: true }).click();
  await expect(page.getByText('Publicado', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/learning-published-desktop.png', fullPage: true });
  await page.getByRole('navigation').getByRole('button', { name: 'Consolidação anual', exact: true }).click();
  await page.getByLabel('Nome da regra anual').fill(`Anual diário ${suffix}`);
  await page.getByLabel('Ano letivo', { exact: false }).selectOption(calendar.id);
  await page.getByLabel('Escala, aprovação e recuperação final').selectOption({ label: `Regra diário ${suffix}` });
  await page.getByRole('button', { name: 'Salvar regra anual', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Regra anual salva');
  await page.getByLabel('Regra anual', { exact: true }).selectOption({ label: `Anual diário ${suffix}` });
  await page.getByRole('combobox', { name: 'Aluno', exact: true }).selectOption(student.id);
  await page.getByRole('button', { name: 'Consultar consolidação' }).click();
  await expect(page.getByRole('cell', { name: '8.0', exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Publicar resultado anual' }).click();
  await expect(page.getByRole('status')).toContainText('Resultado anual publicado');

  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await page.getByLabel('E-mail', { exact: true }).fill('guardian@aurora.example.com');
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar no portal', exact: true }).click();
  await page.getByText(student.name, { exact: true }).locator('..').getByRole('button', { name: 'Ver boletim' }).click();
  await expect(page.getByText('Aprovado no período', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: new RegExp(`Resultado anual · ${year}`) })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/learning-family-mobile.png', fullPage: true });
});
